import type { ComponentType } from "react";
import type { ExploreState } from "@/pages/explore/exploreState";


export type ExploreQuadrant = 'Capacity' | 'Workforce' | 'Revenue' | 'Quality';

export type DriverScaleAxis = 'providers' | 'encounters' | 'patientDays' | 'fixed';
export type ExploreSetting = 'outpatient' | 'ed' | 'inpatient' | 'nursing';
export type ExploreDriverVisibility = 'quantified' | 'qualitative';

export interface ExploreCalcComponentProps {
  state: ExploreState;
  updateTimeDriverInputs: (updates: Partial<ExploreState['timeDriverInputs']>) => void;
  updateDocQualityInputs: (updates: Partial<ExploreState['docQualityInputs']>) => void;
  totalHoursSaved: number;
}

export interface ExploreDriverMeasureDefaults {
  deltaLabel: string;
  deltaUnit: string;
  valuePerUnitLabel: string;
  valuePerUnitDefault: number;
  valuePerUnitPrefix?: string;
  valuePerUnitSuffix?: string;
  /** Legacy Explore-era field, unused by the Measure value math (attribution only). Optional so it can be dropped as drivers are remodeled. */
  realizationDefault?: number;
  scaleAxis: DriverScaleAxis;
  benchmarkHint?: string;
  lowerIsBetter?: boolean;
  emCodes?: Array<{ code: string; label: string; section?: string }>;
  highComplexityCodes?: string[];
  scaleInput?: { label: string; defaultValue: number; unit: string; divisor: number };
  isPerEncounterRate?: boolean;
  /** Optional risk-adjustment program selector (e.g. MA / Medicaid MCO / ACA). Drives the panel terminology; value-per-unit stays user-set. */
  populationOptions?: string[];
  /** Render one "amount" input instead of before/after (the value IS the gain, e.g. additional visits created). */
  singleValueEntry?: boolean;
  /** Before/after are entered directly in dollars; the value is the difference. Hides the value-per-unit field. */
  dollarLevel?: boolean;
  /** Allow breaking the metric out into per-service-line rows (select-or-type). Metric is never meaningful at the aggregate. */
  serviceLineBreakdown?: boolean;
  /** Preset service lines offered in the select-or-type field (users can still type their own). */
  serviceLineOptions?: string[];
}

export interface ValueArcStage {
  timing: string;
  metric: string;
}

export interface ValueArc {
  signal?: ValueArcStage;
  trend?: ValueArcStage;
  proof?: ValueArcStage;
}

