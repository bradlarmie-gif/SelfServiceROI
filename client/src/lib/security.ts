export function sanitizeNumber(value: string | number, min = 0, max = Infinity): number | null {
  const num = typeof value === 'string' ? parseFloat(value) : value;
  if (isNaN(num)) return null;
  if (num < min) return min;
  if (num > max) return max;
  return Math.round(num * 100) / 100;
}

export function sanitizePercentage(value: string | number): number | null {
  const num = typeof value === 'string' ? parseFloat(value) : value;
  if (isNaN(num)) return null;
  return Math.min(100, Math.max(0, num));
}

export function sanitizeText(value: string): string {
  if (!value) return '';
  return value
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;')
    .trim()
    .slice(0, 500);
}

export function bucketValue(value: number, buckets: { max: number; label: string }[]): string {
  for (const bucket of buckets) {
    if (value <= bucket.max) {
      return bucket.label;
    }
  }
  return buckets[buckets.length - 1].label;
}

