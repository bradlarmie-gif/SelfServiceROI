const rateLimiter = {
  calls: {} as Record<string, number[]>,
  
  canMakeCall(endpoint: string, maxCalls = 10, windowMs = 60000): boolean {
    const now = Date.now();
    const key = endpoint;
    
    if (!this.calls[key]) {
      this.calls[key] = [];
    }
    
    this.calls[key] = this.calls[key].filter(time => now - time < windowMs);
    
    if (this.calls[key].length >= maxCalls) {
      return false;
    }
    
    this.calls[key].push(now);
    return true;
  }
};

export { rateLimiter };
